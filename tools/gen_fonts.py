#!/usr/bin/env python3
"""Generate the LVGL bitmap fonts from the IBM Plex TTFs in assets/fonts/src.

Output: app/src/ui/fonts/font_*.c (committed, so a normal build needs no Node).
Needs: `npm install` in tools/fontconv (lv_font_conv).
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "fonts" / "src"
OUT = ROOT / "app" / "src" / "ui" / "fonts"
CONV = ROOT / "tools" / "fontconv" / "node_modules" / "lv_font_conv" / "lv_font_conv.js"

ASCII = "0x20-0x7E"
# degree, plus-minus, micro, middle dot, multiply, en dash, bullet, arrows
EXTRA = "0xB0,0xB1,0xB5,0xB7,0xD7,0x2013,0x2022,0x2190-0x2193"
DIGITS = "0x20,0x25,0x2B-0x3A,0xB0"  # space % + , - . / 0-9 : degree

# name, ttf, size, ranges
FONTS = [
    ("font_text_14", "IBMPlexSans-Regular.ttf", 14, f"{ASCII},{EXTRA}"),
    ("font_text_16", "IBMPlexSans-Regular.ttf", 16, f"{ASCII},{EXTRA}"),
    ("font_textm_14", "IBMPlexSans-Medium.ttf", 14, f"{ASCII},{EXTRA}"),
    ("font_textm_16", "IBMPlexSans-Medium.ttf", 16, f"{ASCII},{EXTRA}"),
    ("font_textm_20", "IBMPlexSans-Medium.ttf", 20, f"{ASCII},{EXTRA}"),
    ("font_head_20", "IBMPlexSansCondensed-SemiBold.ttf", 20, f"{ASCII},{EXTRA}"),
    ("font_head_28", "IBMPlexSansCondensed-SemiBold.ttf", 28, f"{ASCII},{EXTRA}"),
    ("font_head_40", "IBMPlexSansCondensed-SemiBold.ttf", 40, f"{ASCII},{EXTRA}"),
    ("font_num_32", "IBMPlexSansCondensed-Medium.ttf", 32, DIGITS),
    ("font_num_56", "IBMPlexSansCondensed-Medium.ttf", 56, DIGITS),
    ("font_num_96", "IBMPlexSansCondensed-Medium.ttf", 96, DIGITS),
    ("font_mono_12", "IBMPlexMono-Medium.ttf", 12, f"{ASCII},{EXTRA}"),
    ("font_mono_14", "IBMPlexMono-Medium.ttf", 14, f"{ASCII},{EXTRA}"),
]


def main() -> None:
    if not CONV.exists():
        sys.exit("lv_font_conv missing: run `npm install` in tools/fontconv")
    OUT.mkdir(parents=True, exist_ok=True)
    decls = []
    for name, ttf, size, ranges in FONTS:
        cmd = ["node", str(CONV), "--font", str(SRC / ttf)]
        for r in ranges.split(","):
            cmd += ["-r", r]
        cmd += ["--size", str(size), "--bpp", "4", "--format", "lvgl", "--no-compress",
                "--lv-include", "lvgl.h", "--lv-font-name", name, "-o", str(OUT / f"{name}.c")]
        subprocess.run(cmd, check=True)
        kb = (OUT / f"{name}.c").stat().st_size / 1024
        print(f"{name:14s} {ttf:36s} {size:3d} px  ({kb:.0f} KB source)")
        decls.append(f"LV_FONT_DECLARE({name});")
    (OUT / "fonts.h").write_text(
        "/* Generated by tools/gen_fonts.py. IBM Plex, SIL Open Font License 1.1. */\n"
        "#ifndef UI_FONTS_H\n#define UI_FONTS_H\n\n#include <lvgl.h>\n\n"
        + "\n".join(decls) + "\n\n#endif\n")


if __name__ == "__main__":
    main()
